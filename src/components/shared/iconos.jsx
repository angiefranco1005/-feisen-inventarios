// Íconos del ERP: familia Phosphor (decisión de Angie, 2026-10-29). Se exportan con los
// nombres que tenían en lucide-react para que cada pantalla solo cambie de dónde importa.
// Peso por defecto: `light` (línea fina, aspecto ERP); en tamaños menores a 16 px pasa a
// `regular` para que no se pierda. El menú y los indicadores usan `weight="duotone"`.
// `strokeWidth` (de lucide) se ignora. Para un ícono nuevo, agrégalo aquí, no importes
// directo de @phosphor-icons/react.

const envolver = (Icono, nombre) => {
  const C = forwardRef(({ size = 24, strokeWidth, weight, ...props }, ref) => (
    <Icono ref={ref} size={size} weight={weight || (Number(size) < 16 ? 'regular' : 'light')} {...props} />
  ))
  C.displayName = nombre
  return C
}

