efectos AS (
  SELECT item_id, bodega_destino_id AS bodega_id, cantidad AS efecto, created_at, id
  FROM public.movimientos
  WHERE bodega_destino_id IS NOT NULL
    AND tipo IN ('entrada_compra','devolucion','entrada','traslado','ajuste_inventario')
  UNION ALL
  SELECT item_id, bodega_origen_id, -cantidad, created_at, id
  FROM public.movimientos
  WHERE bodega_origen_id IS NOT NULL
    AND tipo IN ('salida_produccion','salida_venta','salida','traslado')
),
corrido AS (
  SELECT item_id, bodega_id, efecto,
         SUM(efecto) OVER (PARTITION BY item_id, bodega_id ORDER BY created_at, id, efecto) AS saldo
  FROM efectos
),
resumen AS (
  SELECT item_id, bodega_id,
         SUM(efecto) AS neto_movimientos,
         GREATEST(0, -MIN(saldo)) AS inicial_implicito
  FROM corrido
  GROUP BY item_id, bodega_id
),
base AS (
  SELECT it.nombre AS producto, b.nombre AS bodega,
         COALESCE(s.cantidad_actual, 0) AS stock_sistema,
         r.neto_movimientos,
         c.qty AS stock_inicial_carga,
         r.inicial_implicito,
         r.neto_movimientos + GREATEST(COALESCE(c.qty, 0), r.inicial_implicito) AS esperado,
         COALESCE(s.cantidad_actual, 0)
           - (r.neto_movimientos + GREATEST(COALESCE(c.qty, 0), r.inicial_implicito)) AS desvio,
         it.precio_costo
  FROM resumen r
  JOIN public.items it   ON it.id = r.item_id AND it.activo
  JOIN public.bodegas b  ON b.id = r.bodega_id AND b.nombre = 'ALMACEN'
  LEFT JOIN public.stock s ON s.item_id = r.item_id AND s.bodega_id = r.bodega_id
  LEFT JOIN carga c ON c.nombre = it.nombre
)
SELECT producto, bodega, stock_sistema, neto_movimientos, stock_inicial_carga,
       inicial_implicito, esperado, desvio,
       (stock_inicial_carga IS NOT NULL) AS esta_en_carga_inicial,
       ROUND(desvio * precio_costo) AS valor_desvio_cop,
       -- Lo que daría el stock si TODOS los movimientos fueran correctos: carga inicial + neto
       (COALESCE(stock_inicial_carga, 0) + neto_movimientos) AS stock_segun_historial,
       -- Unidades que el piso de 0 del trigger "se comió" (salidas registradas antes que su entrada)
       GREATEST(0, inicial_implicito - COALESCE(stock_inicial_carga, 0)) AS perdido_por_piso,
       ROUND(GREATEST(0, inicial_implicito - COALESCE(stock_inicial_carga, 0)) * precio_costo) AS valor_perdido_por_piso_cop,
       COUNT(*) OVER () AS total_filas
FROM base
WHERE ABS(desvio) > 0.0005
   OR inicial_implicito > COALESCE(stock_inicial_carga, 0)
ORDER BY GREATEST(ABS(desvio * precio_costo),
                  GREATEST(0, inicial_implicito - COALESCE(stock_inicial_carga, 0)) * precio_costo) DESC NULLS LAST
LIMIT 250;
